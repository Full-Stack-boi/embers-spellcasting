/** Class-specific feature rules, kept separate from spell formula overrides. */
export const CLASS_MANUAL_FORMULAS = {
  barbarian: BARBARIAN_CLASS_FORMULAS,
  bard: BARD_CLASS_FORMULAS,
  cleric: CLERIC_CLASS_FORMULAS,
  druid: DRUID_CLASS_FORMULAS,
  fighter: FIGHTER_CLASS_FORMULAS,
  gunslinger: GUNSLINGER_CLASS_FORMULAS,
  monk: MONK_CLASS_FORMULAS,
  paladin: PALADIN_CLASS_FORMULAS,
  ranger: RANGER_CLASS_FORMULAS,
  rogue: ROGUE_CLASS_FORMULAS,
  sorcerer: SORCERER_CLASS_FORMULAS,
  warlock: WARLOCK_CLASS_FORMULAS,
  wizard: WIZARD_CLASS_FORMULAS,
  monsterHunter: MONSTER_HUNTER_CLASS_FORMULAS,
  artificer: ARTIFICER_CLASS_FORMULAS,
} as const;

export const ALL_MANUAL_ACTION_FORMULAS: Record<string, ManualActionFormula> =
  Object.values(CLASS_MANUAL_FORMULAS)
    .flatMap((classFormulas) => Object.values(classFormulas))
    .reduce<Record<string, ManualActionFormula>>((all, formula) => {
      all[formula.id] = formula;
      return all;
    }, {});

export function findMatchingActionFormula(featureName: string): ManualActionFormula | undefined {
  if (!featureName) return undefined;
  const norm = featureName.toLowerCase().trim();
  return Object.values(ALL_MANUAL_ACTION_FORMULAS).find((f) => {
    const fName = f.name.toLowerCase().trim();
    return fName === norm || norm.includes(fName) || fName.includes(norm);
  });
}


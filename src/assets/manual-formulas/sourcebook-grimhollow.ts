import type { SpellFormula } from "../../types/spellFormula";

/**
 * Grim Hollow: Player’s Guide (Ghostfire Gaming / 2024 Partner Supplement)
 * 101 modern revised spells verified against D&D Beyond.
 */
function makeGrimHollowSpell(input: {
  id: string;
  name: string;
  level: number;
  school: SpellFormula["category"]["school"];
  classes: string[];
  source: string;
  time: string;
  range: string;
  components: string;
  duration: string;
  interaction?: SpellFormula["interaction"];
  damage?: SpellFormula["damage"];
  scaling?: SpellFormula["cantripScale"];
  upcasting?: SpellFormula["upcasting"];
  effectNotes?: string[];
}): SpellFormula {
  const isConcentration = input.duration
    .toLowerCase()
    .includes("concentration");
  const isRitual = input.time.toLowerCase().includes("ritual");

  return {
    id: input.id,
    name: input.name,
    category: {
      spellType: input.level === 0 ? "cantrip" : "spell",
      school: input.school,
      level: input.level,
      classes: input.classes,
      source: input.source,
      concentration: isConcentration,
      ritual: isRitual,
    },
    casting: {
      time: input.time,
      range: input.range,
      components: input.components,
      duration: input.duration,
    },
    interaction: input.interaction,
    damage: input.damage ?? [],
    cantripScale: input.scaling,
    upcasting: input.upcasting,
    effectNotes: input.effectNotes,
    implementation: {
      sourceStatus: "checked",
      runtimeStatus:
        input.interaction || input.damage?.length ? "assisted" : "manual",
      playtestStatus: "not-tested",
      manualSteps: [
        "Review the result and apply HP changes on the character sheet; spell rolls do not update Owlbear token HP.",
        ...(input.effectNotes ?? [
          "Resolve this spell's effect with the GM; no automatic effect is applied to tokens.",
        ]),
      ],
    },
    isManualOverride: true,
  };
}

